#!/usr/bin/env python3
"""Compile engine/shaders/*.hlsl to SPIR-V C headers for the NVRHI backends.

The generated headers (engine/src/backends/nvrhi/shaders/*.h) are committed,
so building the game needs no shader compiler. Run this after editing a
shader:

    python tools/compile_shaders.py            # regenerate
    python tools/compile_shaders.py --check    # fail if a header is stale

Needs dxc from the Vulkan SDK (VULKAN_SDK set, or dxc on PATH).
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "engine" / "shaders"
OUT = ROOT / "engine" / "src" / "backends" / "nvrhi" / "shaders"

# (source, entry point, stage profile, C array name)
SHADERS = [
    ("box.hlsl", "main_vs", "vs_6_0", "g_box_vs_spirv"),
    ("box.hlsl", "main_ps", "ps_6_0", "g_box_ps_spirv"),
    ("box.hlsl", "main_ps_mv", "ps_6_0", "g_box_ps_mv_spirv"),
    ("gltf.hlsl", "main_vs", "vs_6_0", "g_gltf_vs_spirv"),
    ("gltf.hlsl", "main_ps", "ps_6_0", "g_gltf_ps_spirv"),
    ("composite.hlsl", "main_vs", "vs_6_0", "g_composite_vs_spirv"),
    ("composite.hlsl", "main_ps", "ps_6_0", "g_composite_ps_spirv"),
]

# No -fvk-invert-y: NVRHI's Vulkan backend already sets a D3D-style
# (negative-height) viewport, so clip space is Y-up as in OpenGL/D3D.
# NVRHI's default Vulkan binding offsets (nvrhi::VulkanBindingOffsets):
# t# -> 0+, s# -> 128+, b# -> 256+, u# -> 384+.
SPIRV_FLAGS = [
    "-spirv", "-fspv-target-env=vulkan1.2",
    "-fvk-t-shift", "0", "0",
    "-fvk-s-shift", "128", "0",
    "-fvk-b-shift", "256", "0",
    "-fvk-u-shift", "384", "0",
    "-O3",
]


def find_dxc():
    sdk = os.environ.get("VULKAN_SDK")
    if sdk:
        for sub in ("Bin", "bin"):
            for name in ("dxc.exe", "dxc"):
                p = Path(sdk) / sub / name
                if p.exists():
                    return str(p)
    found = shutil.which("dxc")
    if found:
        return found
    sys.exit("compile_shaders: dxc not found (install the Vulkan SDK and set VULKAN_SDK)")


def to_header(spirv: bytes, var: str, source: str, entry: str) -> str:
    lines = [
        f"// Generated by tools/compile_shaders.py from engine/shaders/{source} ({entry}).",
        "// Do not edit: change the HLSL source and re-run the script.",
        "#pragma once",
        "#include <cstddef>",
        "",
        f"static const unsigned char {var}[] = {{",
    ]
    for i in range(0, len(spirv), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in spirv[i:i + 16]) + ",")
    lines.append("};")
    lines.append(f"static const std::size_t {var}_size = sizeof({var});")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="only verify the headers are current")
    args = parser.parse_args()

    dxc = find_dxc()
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    with tempfile.TemporaryDirectory() as tmp:
        for source, entry, profile, var in SHADERS:
            spv = Path(tmp) / f"{var}.spv"
            cmd = [dxc, *SPIRV_FLAGS, "-T", profile, "-E", entry, str(SRC / source), "-Fo", str(spv)]
            result = subprocess.run(cmd, capture_output=True, text=True)
            if result.returncode != 0:
                sys.exit(f"compile_shaders: {source}:{entry} failed\n{result.stderr}")
            header = to_header(spv.read_bytes(), var, source, entry)
            target = OUT / f"{var}.h"
            current = target.read_text() if target.exists() else ""
            if current != header:
                stale.append(target.name)
                if not args.check:
                    target.write_text(header, newline="\n")
    if args.check and stale:
        sys.exit("compile_shaders: stale headers: " + ", ".join(stale))
    print("compile_shaders: " + ("up to date" if not stale else "wrote " + ", ".join(stale)))


if __name__ == "__main__":
    main()
